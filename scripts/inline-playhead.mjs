#!/usr/bin/env node
/**
 * Keep one copy of the playhead arithmetic while it lives in two places.
 *
 * `client.js` is loaded by the host's module loader as a single classic script
 * and can only `require('react')` — no relative import, no bundler, no build
 * step (D-02). `node --test` cannot import a browser bundle either. So the pure
 * module `lib/shared/playhead.js` is *rendered into* `client.js` between two
 * markers, in the same spirit as `scripts/bundle-id.mjs --write` stamping one
 * line: the generated thing is small, and a guard test fails while it is stale.
 *
 * Edit the module, then `--write`. Nothing else should touch the block.
 *
 * Usage:
 *   node scripts/inline-playhead.mjs            # verify; exit 1 when stale
 *   node scripts/inline-playhead.mjs --write    # rewrite the block in client.js
 *
 * Exit codes: 0 = consistent (or written), 1 = stale, 3 = usage/module error.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))

/** Repo root (this script lives in `scripts/`). */
export const REPO = join(HERE, '..')
/** The single source of truth for the arithmetic. */
export const MODULE_FILE = join(REPO, 'lib', 'shared', 'playhead.js')
/** The bundle that carries the generated copy. */
export const CLIENT_FILE = join(REPO, 'client.js')

const INDENT = '    '
/** Marker lines; both carry the path so a reader landing mid-block knows the source. */
export const BEGIN = `${INDENT}/* ── BEGIN inlined lib/shared/playhead.js ── generated by \`node scripts/inline-playhead.mjs --write\`; edit the module, never this copy ── */`
export const END = `${INDENT}/* ── END inlined lib/shared/playhead.js ── */`
/** Where the block goes on first insert: right above the function that uses it. */
const ANCHOR = `${INDENT}function estimateMs(player) {`

/** Windows checkouts and Linux CI must agree. */
const normalizeEol = (text) => text.replace(/\r\n/g, '\n')

/** Preserve whatever the file already uses; rewriting EOLs would hide the real diff. */
const eolOf = (text) => (text.includes('\r\n') ? '\r\n' : '\n')

/**
 * Render the module as the block `client.js` carries.
 *
 * `export` is stripped (the module shares client.js's factory scope) and every
 * line is indented to the factory's level. Anything else that only works in a
 * module — an `import`, a re-`export` — is a hard error rather than a silently
 * broken bundle.
 * @param {string} moduleSource contents of `lib/shared/playhead.js`
 * @returns {string}
 */
export function renderBlock(moduleSource) {
  const body = normalizeEol(moduleSource).split('\n')
  while (body.length > 0 && body[body.length - 1].trim() === '') body.pop()
  const inlinable = body.map((line) => line.replace(/^export /, ''))
  for (const line of inlinable) {
    if (/^\s*import\s/.test(line)) throw new Error('inline-playhead: the module imports something; it must stay self-contained')
    if (/^\s*export\b/.test(line)) throw new Error(`inline-playhead: unsupported export form: ${line.trim()}`)
  }
  const indented = inlinable.map((line) => (line === '' ? '' : INDENT + line))
  return [BEGIN, ...indented, END].join('\n')
}

/**
 * The block currently in `client.js`, markers included.
 * @param {string} source
 * @returns {string|null} `null` when the markers are absent
 */
export function extractBlock(source) {
  const text = normalizeEol(source)
  const start = text.indexOf(BEGIN)
  if (start < 0) return null
  const end = text.indexOf(END, start)
  if (end < 0) return null
  return text.slice(start, end + END.length)
}

/**
 * Put `block` into `source`, replacing the existing one or inserting on first run.
 * @param {string} source
 * @param {string} block
 * @returns {string}
 */
export function applyBlock(source, block) {
  const eol = eolOf(source)
  const text = normalizeEol(source)
  const wanted = normalizeEol(block)
  const existing = extractBlock(text)
  let next
  if (existing !== null) {
    const at = text.indexOf(existing)
    next = text.slice(0, at) + wanted + text.slice(at + existing.length)
  } else {
    const at = text.indexOf(ANCHOR)
    if (at < 0) throw new Error(`inline-playhead: no anchor in client.js (expected a line "${ANCHOR.trim()}")`)
    next = `${text.slice(0, at)}${wanted}\n\n${text.slice(at)}`
  }
  return eol === '\n' ? next : next.replace(/\n/g, eol)
}

function run(argv) {
  if (argv.includes('--help') || argv.includes('-h')) {
    process.stdout.write('usage: node scripts/inline-playhead.mjs [--write]\n')
    return 0
  }
  const block = renderBlock(readFileSync(MODULE_FILE, 'utf8'))
  const source = readFileSync(CLIENT_FILE, 'utf8')
  const current = extractBlock(source)
  const fresh = current === normalizeEol(block)

  if (argv.includes('--write')) {
    if (fresh) {
      process.stdout.write('inlined playhead already current; nothing written\n')
      return 0
    }
    writeFileSync(CLIENT_FILE, applyBlock(source, block))
    const verify = extractBlock(readFileSync(CLIENT_FILE, 'utf8'))
    if (verify !== normalizeEol(block)) throw new Error('inline-playhead: write produced a different block')
    process.stdout.write(`${current === null ? 'inserted' : 'rewrote'} the inlined playhead block (${block.split('\n').length} lines)\n`)
    return 0
  }

  if (fresh) {
    process.stdout.write('inlined playhead matches lib/shared/playhead.js\n')
    return 0
  }
  process.stdout.write(`${current === null ? 'client.js has no inlined playhead block' : 'the inlined playhead block is stale'}\n`
    + 'run `node scripts/inline-playhead.mjs --write`\n')
  return 1
}

const invokedDirectly = process.argv[1] !== undefined
  && import.meta.url === pathToFileURL(process.argv[1]).href

if (invokedDirectly) {
  try {
    process.exitCode = run(process.argv.slice(2))
  } catch (error) {
    process.stderr.write(`${error?.message ?? error}\n`)
    process.exitCode = 3
  }
}
